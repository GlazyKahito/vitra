"""Generate SYNTHETIC fixtures: six strip images + a 240-row calibration CSV.

Usage: python tools/make_fixtures.py [out_dir]   (default: services/cv/fixtures)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from vitra_cv.config import ANALYTE_KEYS  # noqa: E402
from vitra_cv.synthetic import render_strip, synthetic_dataset  # noqa: E402

FIXTURES = [
    # (seed, kwargs, note)
    (11, dict(rotation_deg=0.0, levels={"glucose": 0.15}), "clean, horizontal, low glucose"),
    (12, dict(rotation_deg=2.5, levels={"glucose": 0.85}), "slight tilt, high glucose"),
    (13, dict(rotation_deg=-9.0, levels={k: 0.5 for k in ANALYTE_KEYS}), "tilted, all pads mid-level"),
    (14, dict(blur=8.0), "BLURRY (should fail blur check)"),
    (15, dict(exposure=1.9), "OVEREXPOSED (should fail overexposure check)"),
    (16, dict(rotation_deg=90.0, width=640, height=1600), "rotated 90 degrees (portrait capture)"),
]


def main(out_dir: str) -> None:
    os.makedirs(out_dir, exist_ok=True)
    lines = ["# Fixtures — ALL SYNTHETIC", "",
             "Every file in this directory is generated by `tools/make_fixtures.py` from",
             "`vitra_cv.synthetic`. Nothing here is a real strip, a real patient sample or",
             "real reagent chemistry. Pad colours follow the demo ramps in",
             "`apps/web/lib/analytes.ts`. Do not present these as measurements.", "",
             "| file | seed | description |", "|---|---|---|"]
    for i, (seed, kw, note) in enumerate(FIXTURES, start=1):
        name = f"synthetic_strip_{i:02d}.png"
        with open(os.path.join(out_dir, name), "wb") as f:
            f.write(render_strip(seed=seed, **kw))
        lines.append(f"| {name} | {seed} | {note}; params `{kw}` |")
    df = synthetic_dataset(240, seed=1)
    df.to_csv(os.path.join(out_dir, "synthetic_calibration_v1.csv"), index=False)
    lines += ["| synthetic_calibration_v1.csv | 1 | 240 rows, 3 batches, `synthetic=true`, "
              "nonlinear forward colour model + noise + mild cross-pad interaction |", ""]
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(FIXTURES)} images + CSV to {out_dir}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(HERE), "fixtures"))
