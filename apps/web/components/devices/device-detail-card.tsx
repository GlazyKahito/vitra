import type { ReactNode } from "react";
import type { DeviceWithHealth } from "@/lib/data/contract";
import { Chip } from "@/components/ui/chip";
import { formatDateTime, formatRelative } from "@/lib/utils";
import { DeviceKindTag, HealthChip, captureState } from "./device-table";

function Row({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="flex items-start justify-between gap-4 border-b border-line py-2 last:border-b-0">
      <dt className="t-eyebrow pt-0.5">{label}</dt>
      <dd className="min-w-0 text-right text-[13px] text-fg-2">{children}</dd>
    </div>
  );
}

export function DeviceDetailCard({ d }: { d: DeviceWithHealth }) {
  const dev = d.device;
  const illum = dev.illuminationProfile ?? null;
  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-wrap items-center gap-2">
        <DeviceKindTag device={dev} />
        <HealthChip health={d.health} />
        {dev.simulated ? <span className="text-[12px] text-fg-4">All readings below are generated by the simulated adapter.</span> : null}
        {!dev.simulated && d.health === "offline" ? <span className="text-[12px] text-fg-4">No telemetry has been received from this hardware.</span> : null}
      </div>
      <dl className="flex flex-col">
        <Row label="Device id">
          <span className="t-mono">{dev.id}</span>
        </Row>
        <Row label="Hardware id">
          <span className="t-mono">{dev.hardwareId ?? "—"}</span>
        </Row>
        <Row label="Kind">
          <span className="t-mono">{dev.kind}</span>
        </Row>
        <Row label="Connectivity">
          {dev.lastSeenAt ? (
            <span>
              {formatRelative(dev.lastSeenAt)} <span className="t-mono text-[11px] text-fg-4">({formatDateTime(dev.lastSeenAt, { seconds: true })})</span>
            </span>
          ) : (
            "never seen"
          )}
        </Row>
        <Row label="Camera">
          <span className="flex flex-col items-end">
            <span>{dev.cameraModel ?? "—"}</span>
            <span className="t-mono text-[11px] text-fg-4">{dev.simulated ? "simulated camera" : d.lastCapture ? captureState(d) : "state unknown"}</span>
          </span>
        </Row>
        <Row label="Capture state">{captureState(d)}</Row>
        <Row label="Illumination">
          {illum ? (
            <span className="t-mono text-[11.5px]">
              {Object.entries(illum)
                .slice(0, 6)
                .map(([k, v]) => `${k}=${typeof v === "object" ? JSON.stringify(v) : String(v)}`)
                .join(" · ")}
            </span>
          ) : (
            "no profile"
          )}
        </Row>
        <Row label="Software">
          <span className="t-mono">{dev.softwareVersion ?? "—"}</span>
        </Row>
        <Row label="Calibration profile">
          <span className="t-mono">{dev.calibrationProfileId ?? "none"}</span>
        </Row>
        <Row label="Errors 24h">
          <span className={d.errorCount24h > 0 ? "t-mono text-fault" : "t-mono"}>{d.errorCount24h}</span>
        </Row>
        <Row label="Ingest key">{dev.apiKeyHash ? <Chip tone="neutral">configured</Chip> : <Chip tone="muted">none</Chip>}</Row>
        <Row label="Registered">
          <span className="t-mono text-[12px]">{formatDateTime(dev.createdAt)}</span>
        </Row>
      </dl>
    </div>
  );
}
