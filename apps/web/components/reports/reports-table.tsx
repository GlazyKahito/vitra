import Link from "next/link";
import { EmptyState } from "@/components/ui/empty-state";
import type { Report, Run, Sample } from "@/lib/data/contract";
import { Chip } from "@/components/ui/chip";
import { SyntheticTag } from "@/components/common/synthetic-tag";
import { formatDateTime, shortId } from "@/lib/utils";

export type ReportRow = Report & { run: Run; sample: Sample; generatedByLabel?: string | null };

function bytes(n: number): string {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / 1024 / 1024).toFixed(2)} MB`;
}

export function ReportsTable({ reports, canDownload }: { reports: ReportRow[]; canDownload: boolean }) {
  if (reports.length === 0) return <EmptyState className="py-12" title="No reports match." description="Generate one from a run below." />;
  return (
    <table className="table-instrument">
      <thead>
        <tr>
          <th>Report</th>
          <th>Run</th>
          <th>Sample</th>
          <th>Format</th>
          <th>Size</th>
          <th>Generated by</th>
          <th>At</th>
          <th />
        </tr>
      </thead>
      <tbody>
        {reports.map((r) => (
          <tr key={r.id}>
            <td className="t-mono text-[12px]">
              {shortId(r.id, 12)}
              <div className="text-[10.5px] text-fg-4">sha256 {shortId(r.sha256, 10)}</div>
            </td>
            <td>
              <Link href={`/history/${encodeURIComponent(r.run.id)}`} className="t-mono text-[12px] text-fg hover:text-signal">
                {r.run.runCode}
              </Link>
              <div className="flex gap-1 pt-0.5">
                <Chip tone="muted">{r.run.mode}</Chip>
                {r.run.synthetic ? <SyntheticTag /> : null}
              </div>
            </td>
            <td className="t-mono text-[12px]">
              {r.sample.sampleCode}
              {r.sample.synthetic ? <span className="ml-1 text-fg-4">(synthetic)</span> : null}
            </td>
            <td>
              <Chip tone="neutral">{r.format}</Chip>
            </td>
            <td className="t-mono">{bytes(r.byteSize)}</td>
            <td className="text-[12.5px]">{r.generatedByLabel ?? (r.generatedById ? shortId(r.generatedById) : "system")}</td>
            <td className="t-mono text-[12px]">{formatDateTime(r.createdAt)}</td>
            <td>
              {canDownload ? (
                <a href={`/api/reports/${encodeURIComponent(r.id)}`} className="text-[12.5px] text-signal underline-offset-2 hover:underline" download>
                  Download
                </a>
              ) : (
                <span className="text-[12px] text-fg-4">no access</span>
              )}
            </td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}
