import Link from "next/link";
import { AppShell } from "@/components/shell/app-shell";
import { Panel } from "@/components/ui/panel";
import { requireUser } from "@/lib/auth";
import { logoutAction } from "@/lib/auth/actions";
import { listDevices } from "@/lib/data/devices";
import { PrototypeBanner } from "@/components/common/prototype-banner";
import { DeviceTable } from "@/components/devices/device-table";
import { DeviceDetailCard } from "@/components/devices/device-detail-card";
import { EventTimeline } from "@/components/devices/event-timeline";

export const dynamic = "force-dynamic";

export default async function DevicesPage() {
  const user = await requireUser("runs.read");
  const devices = await listDevices();
  // Highlight: the device with the most recent activity (hardware preferred over simulated when both have events).
  const highlighted =
    [...devices].sort((a, b) => {
      if (a.device.simulated !== b.device.simulated) return a.device.simulated ? 1 : -1;
      return (b.device.lastSeenAt?.getTime() ?? 0) - (a.device.lastSeenAt?.getTime() ?? 0);
    })[0] ?? null;
  const simulatedCount = devices.filter((d) => d.device.simulated).length;
  const hardwareCount = devices.length - simulatedCount;

  return (
    <AppShell user={{ displayName: user.displayName, roleKey: user.roleKey }} eyebrow="08 / Devices" title="Device Monitor" onLogout={logoutAction}>
      <div className="flex flex-col gap-6">
        <PrototypeBanner variant="inline" detail={`${hardwareCount} hardware device${hardwareCount === 1 ? "" : "s"} registered, ${simulatedCount} simulated. Simulated values are generated by the adapter and are marked as such; no live telemetry is shown unless a device has actually posted it.`} />

        <div className="grid grid-cols-[minmax(0,1fr)_420px] items-start gap-6">
          <Panel eyebrow="Fleet" title={`${devices.length} device${devices.length === 1 ? "" : "s"}`} flush>
            <DeviceTable devices={devices} selectedId={highlighted?.device.id} />
          </Panel>

          {highlighted ? (
            <div className="flex flex-col gap-4">
              <Panel
                eyebrow="Highlighted"
                title={highlighted.device.name}
                actions={
                  <Link href={`/devices/${encodeURIComponent(highlighted.device.id)}`} className="text-[12.5px] text-signal hover:underline">
                    Open detail
                  </Link>
                }
              >
                <DeviceDetailCard d={highlighted} />
              </Panel>
              <Panel eyebrow="Recent events" title={`Last ${highlighted.recentEvents.length}`} flush>
                <EventTimeline events={highlighted.recentEvents} emptyText="No events yet." />
              </Panel>
            </div>
          ) : (
            <Panel eyebrow="Highlighted" title="No device">
              <p className="text-[12.5px] text-fg-4">Register a device to see its health here.</p>
            </Panel>
          )}
        </div>

        <PrototypeBanner />
      </div>
    </AppShell>
  );
}
